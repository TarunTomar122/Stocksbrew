from datetime import datetime
import os

def convert_markdown_to_html(markdown_content):
    """Convert the markdown content to styled HTML."""
    # Basic CSS styles
    css = """
    <style>
        body {
            font-family: Arial, sans-serif;
            line-height: 1.6;
            color: #333;
            max-width: 800px;
            margin: 0 auto;
            padding: 20px;
        }
        h1 {
            color: #2c3e50;
            border-bottom: 2px solid #3498db;
            padding-bottom: 10px;
            margin-top: 30px;
        }
        h2 {
            color: #2980b9;
            margin-top: 25px;
        }
        .section {
            background: #f9f9f9;
            border-left: 4px solid #3498db;
            padding: 15px;
            margin: 20px 0;
            border-radius: 0 5px 5px 0;
        }
        .highlight {
            background-color: #fff3cd;
            padding: 2px 5px;
            border-radius: 3px;
        }
        .sentiment {
            font-weight: bold;
            color: #27ae60;
        }
        .warning {
            color: #e74c3c;
        }
        .divider {
            border-top: 1px solid #eee;
            margin: 20px 0;
        }
        .footer {
            margin-top: 40px;
            padding-top: 20px;
            border-top: 2px solid #3498db;
            font-size: 0.9em;
            color: #7f8c8d;
        }
    </style>
    """
    
    # Convert markdown sections to HTML with styling
    html_content = markdown_content.replace(
        "###", "<h2>"
    ).replace("\n\n", "</div><div class='section'>")
    
    replacements = [
        ("**", "</span><span class='highlight'>"),
        ("*Sector Sentiment:*", 
         "<strong class='sentiment'>Sector Sentiment:</strong>"),
        ("*Investment Rating:*", "<strong>Investment Rating:</strong>"),
        ("*Outlook:*", "<strong>Outlook:</strong>"),
        ("*Key Development:*", "<strong>Key Development:</strong>"),
        ("---", "<div class='divider'></div>")
    ]
    
    for old, new in replacements:
        html_content = html_content.replace(old, new)
    
    # Format the date for the title
    date_str = datetime.now().strftime('%B %d, %Y')
    
    # Wrap the content in HTML structure
    html = f"""
    <html>
    <head>
        <meta charset="UTF-8">
        {css}
    </head>
    <body>
        <h1>Stock Market Analysis Report - {date_str}</h1>
        <div class='section'>
            {html_content}
        </div>
        <div class='footer'>
            <p>Generated by Stock Market Analysis Bot</p>
            <p>For questions or feedback, please reply to this email.</p>
        </div>
    </body>
    </html>
    """
    
    return html


def main():
    # Path to the newsletter file
    date_str = datetime.now().strftime('%Y%m%d')
    newsletter_file = f"newsletter_{date_str}.md"
    newsletter_path = os.path.join('stock_summaries', newsletter_file)
    
    if not os.path.exists(newsletter_path):
        print(f"❌ Newsletter file not found at: {newsletter_path}")
        return
    
    print(f"Reading newsletter from: {newsletter_path}")
    
    # Read the newsletter content
    with open(newsletter_path, 'r', encoding='utf-8') as f:
        newsletter_content = f.read()
    
    # Convert to HTML
    html_content = convert_markdown_to_html(newsletter_content)
    
    # Save the HTML file
    output_file = f"newsletter_preview_{date_str}.html"
    with open(output_file, 'w', encoding='utf-8') as f:
        f.write(html_content)
    
    print(f"✅ HTML preview generated: {output_file}")
    print("Open this file in your web browser to see how the newsletter looks!")


if __name__ == "__main__":
    main()