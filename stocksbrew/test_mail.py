def send_email(subject, body):
    print("\nStarting email process...")
    print(f"From: {EMAIL_FROM['email']}")
    print(f"To: {EMAIL_TO[0]['email']}")
    
    try:
        # Configure API key
        configuration = sib_api_v3_sdk.Configuration()
        configuration.api_key['api-key'] = API_KEY

        # Create an instance of the API class
        api_instance = sib_api_v3_sdk.TransactionalEmailsApi(
            sib_api_v3_sdk.ApiClient(configuration)
        )
        
        # Wrap the newsletter content with email-specific styling
        wrapped_body = wrap_newsletter_content(body)
        
        # Create email object with HTML content
        send_smtp_email = sib_api_v3_sdk.SendSmtpEmail(
            to=EMAIL_TO,
            sender=EMAIL_FROM,
            subject=subject,
            html_content=wrapped_body,
            text_content="Please view this email in an HTML-capable email client."
        )
        
        print("Sending email via Brevo API...")
        api_response = api_instance.send_transac_email(send_smtp_email)
        print("✅ Email sent successfully!")
        print(f"Message ID: {api_response.message_id}")
        
    except ApiException as e:
        print("❌ API error occurred!")
        print(f"Error code: {e.reason}")
        print(f"Error details: {e.body}")
    except Exception as e:
        print("❌ An unexpected error occurred!")
        print(f"Error type: {type(e).__name__}")
        print(f"Error details: {str(e)}")


def main():
    # Path to the newsletter file
    newsletter_file = "newsletter.html"
    subject = "Your Daily Stock Market Update ☕"
    
    if not os.path.exists(newsletter_file):
        print(f"❌ Newsletter file not found at: {newsletter_file}")
        return
    
    print(f"Reading newsletter from: {newsletter_file}")
    
    # Read the newsletter content
    with open(newsletter_file, 'r', encoding='utf-8') as f:
        newsletter_content = f.read()
    
    # Extract just the body content from the newsletter
    start = newsletter_content.find('<main>')
    end = newsletter_content.find('</main>')
    if start != -1 and end != -1:
        # Get content between main tags
        content = newsletter_content[start + len('<main>'):end].strip()
    else:
        # Fallback to using the whole content
        content = newsletter_content

    send_email(subject, content)


if __name__ == "__main__":
    main() 