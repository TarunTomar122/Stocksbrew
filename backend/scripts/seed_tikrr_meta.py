def _build_stock_registry(sectors: dict[str, dict], exchange: str, currency: str) -> dict[str, dict]:
    stocks: dict[str, dict] = {}
    for sector_id, sector_payload in sectors.items():
        sector_slug = SECTOR_FIELD_MAP[sector_id]
        for symbol in sector_payload["stocks"]:
            stocks.setdefault(symbol, {
                "name": NAME_MAP.get(symbol, symbol),
                "sector": sector_slug,
                "cap": CAP_MAP.get(symbol, "large"),
                "exchange": exchange,
                "currency": currency,
                "logo": f"https://tikrr.online/logos/{symbol}.png",
            })
    return stocks


def main() -> None:
    store = TraceMoneyStore()
    now = datetime.now(timezone.utc).isoformat()

    stocks_payload = {
        "us": _build_stock_registry(US_SECTORS, "NASDAQ", "USD"),
        "india": _build_stock_registry(IN_SECTORS, "NSE", "INR"),
        "updatedAt": now,
    }
    sectors_payload = {
        "us": US_SECTORS,
        "india": IN_SECTORS,
        "updatedAt": now,
    }
    schedule_payload = {
        **SCHEDULE,
        "updatedAt": now,
    }

    store.db.collection("meta").document("stocks").set(stocks_payload)
    store.db.collection("meta").document("sectors").set(sectors_payload)
    store.db.collection("meta").document("schedule").set(schedule_payload)

    # Seed tikrrEvalUniverse from the eval universe config so the frontend
    # search can show all 150+ stocks even before the LLM pipeline has run.
    eval_universe = _load_eval_universe()
    if eval_universe:
        us_symbols = eval_universe.get("US", [])
        in_symbols = eval_universe.get("IN", [])
        eval_payload = {
            "US": {
                "symbols": us_symbols,
                "sectorIds": list(US_SECTORS.keys()),
                "lastUpdated": now,
            },
            "IN": {
                "symbols": in_symbols,
                "sectorIds": list(IN_SECTORS.keys()),
                "lastUpdated": now,
            },
            "updatedAtServer": now,
        }
        store.db.collection("meta").document("tikrrEvalUniverse").set(eval_payload)
        print(f"  tikrrEvalUniverse: US={len(us_symbols)}, IN={len(in_symbols)}")

    print(
        "Seeded Tikrr meta docs:",
        f"us_stocks={len(stocks_payload['us'])}",
        f"india_stocks={len(stocks_payload['india'])}",
        f"us_sectors={len(US_SECTORS)}",
        f"india_sectors={len(IN_SECTORS)}",
    )


if __name__ == "__main__":
    main()
