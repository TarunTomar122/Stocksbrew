export const LUCIDE_ICON_NAMES = [...new Set(Object.values(MATERIAL_TO_LUCIDE))].sort();

export function lucideFileToExportName(fileStem: string): string {
  const aliases: Record<string, string> = {
    login: "LogInIcon",
    logout: "LogOutIcon",
    "refresh-cw": "RefreshCWIcon",
  };
  if (aliases[fileStem]) return aliases[fileStem];
  const pascal = fileStem
    .split("-")
    .map((part) => part.charAt(0).toUpperCase() + part.slice(1))
    .join("");
  return `${pascal}Icon`;
}
