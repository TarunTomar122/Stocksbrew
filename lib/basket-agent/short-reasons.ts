/**
 * The card line for each company: the short form of our reviewed reason when the company still carries that reason
 * unchanged, else nothing (the card shows the person's own words).
 */
export function shortReasons(
  lines: ReadonlyArray<{ ticker: string; reason: string }>,
  reviewed: (ticker: string) => readonly string[],
): Record<string, string> {
  const out: Record<string, string> = {};
  for (const line of lines) {
    const short = SHORT_REASONS[line.ticker];
    if (short && reviewed(line.ticker).includes(line.reason.trim()))
      out[line.ticker] = short;
  }
  return out;
}
